class WineRecommender:
    def __init__(self, retriever):
        self.retriever = retriever
        self.user_favorites = []

    def display_wine_catalog(self, num_wines=20):
        """Display a catalog of wines for selection"""
        print("🍷 Wine Catalog (first {} wines):".format(num_wines))
        print("=" * 80)

        for i in range(min(num_wines, len(self.retriever.df))):
            wine = self.retriever.df.iloc[i]
            print(f"{i+1}. {wine.get('title', 'No title')}")
            print(f"   📍 {wine.get('variety', 'N/A')} | 🌍 {wine.get('country', 'N/A')} | 💰 ${wine.get('price', 'N/A')}")
            if pd.notna(wine.get('description')):
                desc = str(wine['description'])[:100] + "..." if len(str(wine['description'])) > 100 else wine['description']
                print(f"   📝 {desc}")
            print()

    def add_favorite_wines(self, wine_indices):
        """Add wines to user's favorites list"""
        for idx in wine_indices:
            if 0 <= idx < len(self.retriever.df):
                wine = self.retriever.df.iloc[idx].to_dict()
                if wine not in self.user_favorites:
                    self.user_favorites.append(wine)
                    print(f"✅ Added: {wine.get('title')}")
            else:
                print(f"❌ Wine with index {idx} not found")

    def get_favorites_profile(self):
        """Create a semantic profile of user's favorite wines"""
        if not self.user_favorites:
            return ""

        profile_parts = []
        for wine in self.user_favorites:
            wine_features = []
            if wine.get('variety'): wine_features.append(wine['variety'])
            if wine.get('country'): wine_features.append(wine['country'])
            if wine.get('region_1'): wine_features.append(wine['region_1'])
            if wine.get('description'):
                wine_features.append(wine['description'][:150])

            profile_parts.append(f"{wine.get('title', 'Unknown wine')} ({', '.join(wine_features)})")

        return "User likes wines with characteristics similar to: " + "; ".join(profile_parts)

    def get_similar_recommendations(self, top_k=10):
        """Generate recommendations based on user's favorite wines"""
        if not self.user_favorites:
            print("❌ Please add some favorite wines first!")
            return []

        print("\n🎯 Recommendations based on your preferences:")
        print("=" * 80)

        # Get recommendations based on all favorite wines
        all_recommendations = []
        for favorite in self.user_favorites:
            favorite_description = self._create_wine_description_from_dict(favorite)
            similar_wines = self.retriever.retrieve(favorite_description, top_k=top_k*3)

            # Exclude the favorite wines themselves from recommendations
            similar_wines = [w for w in similar_wines if w.get('title') != favorite.get('title')]
            all_recommendations.extend(similar_wines)

        # Remove duplicates and keep highest similarity scores
        unique_recommendations = {}
        for wine in all_recommendations:
            title = wine.get('title')
            if title not in unique_recommendations or wine['similarity_score'] > unique_recommendations[title]['similarity_score']:
                unique_recommendations[title] = wine

        # Get top-K recommendations
        final_recommendations = sorted(unique_recommendations.values(),
                                     key=lambda x: x['similarity_score'], reverse=True)[:top_k]

        return final_recommendations

    def _create_wine_description_from_dict(self, wine_dict):
        """Create a text description from wine dictionary"""
        desc_parts = []

        if wine_dict.get('title'):
            desc_parts.append(f"Wine: {wine_dict['title']}")

        if wine_dict.get('variety'):
            desc_parts.append(f"Variety: {wine_dict['variety']}")

        if wine_dict.get('country'):
            desc_parts.append(f"Country: {wine_dict['country']}")

        if wine_dict.get('region_1'):
            desc_parts.append(f"Region: {wine_dict['region_1']}")

        if wine_dict.get('description'):
            desc_parts.append(f"Description: {wine_dict['description']}")

        return ". ".join(desc_parts)

    def display_recommendations(self, recommendations):
        """Display recommendations with LLM explanations"""
        if not recommendations:
            print("😞 No suitable recommendations found")
            return

        for i, wine in enumerate(recommendations, 1):
            print(f"\n{i}. 🍷 {wine.get('title', 'No title')}")
            print(f"   📍 Variety: {wine.get('variety', 'N/A')}")
            print(f"   🌍 Country: {wine.get('country', 'N/A')}")
            print(f"   💰 Price: ${wine.get('price', 'N/A')}")
            print(f"   ⭐ Similarity: {wine['similarity_score']:.3f}")

            # Generate explanation based on user's favorites
            favorite_titles = [f["title"] for f in self.user_favorites if f.get('title')]
            explanation_query = f"wines similar to {', '.join(favorite_titles[:2])}"

            print(f"\n   💡 Why we recommend this:")
            explanation = generate_explanation(explanation_query, wine, wine['similarity_score'])

            # Format text with proper wrapping
            import textwrap
            wrapped_text = textwrap.fill(explanation, width=70, initial_indent='   ', subsequent_indent='   ')
            print(wrapped_text)

            print("\n" + "-" * 80)

def interactive_wine_recommendation_system():
    """Interactive wine recommendation system"""

    # Initialize the recommender
    recommender = WineRecommender(retriever)

    print("🎉 Welcome to the Wine Recommendation System!")
    print("Select wines you like, and we'll find similar ones for you!\n")

    while True:
        print("\n" + "=" * 60)
        print("1. 📋 Display Wine Catalog")
        print("2. ❤️  Add Favorite Wines")
        print("3. 👀 Show My Favorites")
        print("4. 🎯 Get Recommendations")
        print("5. 🚪 Exit")
        print("=" * 60)

        choice = input("\nSelect an option (1-5): ").strip()

        if choice == '1':
            # Display catalog
            print("\nLoading wine catalog...")
            recommender.display_wine_catalog(15)

        elif choice == '2':
            # Add favorite wines
            try:
                print("\nEnter the numbers of wines you like (e.g., 1, 3, 5)")
                indices_input = input("Wine numbers: ")
                indices = [int(idx.strip()) - 1 for idx in indices_input.split(',')]
                recommender.add_favorite_wines(indices)
            except ValueError:
                print("❌ Please enter valid numbers separated by commas")

        elif choice == '3':
            # Show current favorites
            if recommender.user_favorites:
                print("\n❤️ Your Favorite Wines:")
                for i, wine in enumerate(recommender.user_favorites, 1):
                    print(f"{i}. {wine.get('title')} - {wine.get('variety')} from {wine.get('country')}")
            else:
                print("❌ You haven't added any favorite wines yet")

        elif choice == '4':
            # Get recommendations
            if not recommender.user_favorites:
                print("❌ Please add some favorite wines first!")
                continue

            try:
                num_recs = input("How many recommendations? (default: 5): ").strip()
                num_recs = int(num_recs) if num_recs else 5

                print("\n🔍 Finding recommendations based on your favorites...")
                recommendations = recommender.get_similar_recommendations(top_k=num_recs)
                recommender.display_recommendations(recommendations)

            except ValueError:
                print("❌ Please enter a valid number")

        elif choice == '5':
            print("👋 Thank you for using our recommendation system!")
            break

        else:
            print("❌ Invalid choice, please try again")

