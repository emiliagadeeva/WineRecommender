            if pd.notna(row.get('aroma')) and row.get('aroma'):
                desc_parts.append(f"Aroma: {row['aroma']}")

            if pd.notna(row.get('sweetness')) and row.get('sweetness'):
                desc_parts.append(f"Sweetness: {row['sweetness']}")

